const { contextBridge, ipcRenderer, webUtils } = require('electron');
contextBridge.exposeInMainWorld('werkbank', {
  setFile: f => { try { if (f instanceof File) return ipcRenderer.invoke('set-file', webUtils.getPathForFile(f)); } catch (e) {} return Promise.resolve(null); },
  tabActivate: id => ipcRenderer.invoke('tab-activate', String(id || '')),
  tabClose: id => ipcRenderer.send('tab-close', String(id || '')),
  tabClaim: t => ipcRenderer.invoke('tab-claim', String(t || '')),
  save: (name, data, saveAs) => ipcRenderer.invoke('save', String(name || ''), data instanceof Uint8Array ? data : null, !!saveAs),
  exportFile: (name, data) => ipcRenderer.invoke('export', String(name || ''), data instanceof Uint8Array ? data : null),
  autoSave: (name, data, fresh) => ipcRenderer.invoke('autosave', String(name || ''), data instanceof Uint8Array ? data : null, !!fresh),
  newDoc: () => ipcRenderer.send('new-doc'),
  log: t => ipcRenderer.send('log', String(t).slice(0, 60000)),
  initial: () => ipcRenderer.invoke('initial-file'),
  onOpen: cb => ipcRenderer.on('open-file', (_e, name, data, t) => cb(name, data, typeof t === 'string' ? t : null)),
  appInfo: () => ipcRenderer.invoke('app-info'),
  checkUpdate: () => ipcRenderer.invoke('check-update'),
  openRelease: u => ipcRenderer.send('open-release', String(u || '')),
  setLang: l => ipcRenderer.send('set-lang', l === 'en' ? 'en' : 'de'),
  recent: () => ipcRenderer.invoke('recent-list'),
  recentOpen: p => ipcRenderer.invoke('recent-open', String(p)),
  recentRemove: p => ipcRenderer.send('recent-remove', String(p)),
  recentClear: () => ipcRenderer.send('recent-clear'),
  recentEnable: on => ipcRenderer.send('recent-enable', !!on),
  renameFile: n => ipcRenderer.invoke('rename-file', String(n || '')),
  spellDict: l => ipcRenderer.invoke('spell-dict', String(l)),
  spellDownload: l => ipcRenderer.invoke('spell-download', String(l)),
  updState: () => ipcRenderer.invoke('upd-state'),
  updDownload: () => ipcRenderer.invoke('upd-download'),
  updInstall: auto => ipcRenderer.invoke('upd-install', !!auto),
  updTerminal: () => ipcRenderer.invoke('upd-terminal'),
  updAutoInstall: on => ipcRenderer.send('upd-auto-install', !!on),
  onUpdProgress: cb => ipcRenderer.on('upd-progress', (_e, got, total) => cb(+got || 0, +total || 0)),
  asrState: () => ipcRenderer.invoke('asr-state'),
  asrInstall: () => ipcRenderer.invoke('asr-install'),
  asrCancel: () => ipcRenderer.send('asr-cancel'),
  asrRemove: () => ipcRenderer.invoke('asr-remove'),
  asrProbe: () => ipcRenderer.invoke('asr-probe'),
  asrStart: () => ipcRenderer.invoke('asr-start'),
  asrStop: () => ipcRenderer.send('asr-stop'),
  asrDecode: s => (s instanceof Float32Array ? ipcRenderer.invoke('asr-decode', s) : Promise.resolve({ error: 'samples' })),
  onAsrProgress: cb => ipcRenderer.on('asr-progress', (_e, phase, got, total) => cb(String(phase), +got || 0, +total || 0)),
});
